#!/usr/bin/env node
// Generates postviewer/css/post-tailwind-responsive.css from post-tailwind.css:
// every utility rule again under Tailwind's sm/md/lg breakpoints, as container queries on the
// post body (see the header of post-tailwind.css). Rerun after every change to post-tailwind.css.
//
//   node postviewer/bin/gen-post-tailwind-responsive.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '../css');
const BREAKPOINTS = [['sm', '40rem'], ['md', '48rem'], ['lg', '64rem']];

/** `.postBody .w-1\/2` → `.postBody .md\:w-1\/2`, for every class but postBody itself. */
const variantSelector = (selector, variant) =>
    selector.replace(/\.((?:[\w-]|\\.)+)/g, (m, cls) => cls == 'postBody' ? m : `.${variant}\\:${cls}`);

export function generate(css) {
    const rules = [...css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/([^{}]+)\{([^{}]*)\}/g)]
        .map(([, selector, body]) => [selector.trim().replace(/\s+/g, ' '), body.trim().replace(/\s+/g, ' ')])
        .filter(([selector]) => /\.(?!postBody\b)[\w\\-]/.test(selector));
    const blocks = BREAKPOINTS.map(([variant, width]) =>
        `@container post-body (min-width: ${width}) {\n`
        + rules.map(([selector, body]) => `  ${variantSelector(selector, variant)} { ${body} }\n`).join('')
        + '}\n');
    return '/* GENERATED by lib/postviewer/bin/gen-post-tailwind-responsive.mjs from post-tailwind.css. Do not edit. */\n\n'
        + blocks.join('\n');
}

if (process.argv[1] == fileURLToPath(import.meta.url)) {
    const out = path.join(dir, 'post-tailwind-responsive.css');
    fs.writeFileSync(out, generate(fs.readFileSync(path.join(dir, 'post-tailwind.css'), 'utf8')));
    console.log(`wrote ${out}`);
}
